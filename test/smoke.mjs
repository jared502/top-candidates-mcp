import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { fileURLToPath } from "node:url";
const entry = fileURLToPath(new URL("../index.js", import.meta.url));
const c = new Client({ name: "smoke", version: "1" });
await c.connect(new StdioClientTransport({ command: "node", args: [entry] }));
const tools = (await c.listTools()).tools.map((t) => t.name);
console.log("TOOLS:", tools.join(", "));
const call = async (name, args) => { const r = await c.callTool({ name, arguments: args }); if (r.isError) throw new Error(name + ": " + r.content[0].text); return r; };
const s = await call("search_top_candidates", { query: "media buyer", maxResults: 5 });
console.log("\n--- search ---\n" + s.content[0].text);
const bad = /@|\+?\d{3}[-.\s]\d{3}|linkedin|\$\s?\d|\/h(ou)?r\b|"[a-z]*(rate|email|phone|address|dob|birth|notes|employer|recruiter|owner|surname|lastName)[a-z]*"\s*:/i;
const leak = (label, r) => { const blob = JSON.stringify(r.structuredContent) + r.content.map((x) => x.text).join(" "); if (bad.test(blob)) throw new Error("leak in " + label + ": " + blob.match(bad)[0]); };
leak("search", s);
const allowed = ["id", "name", "role", "from", "category", "url"];
for (const r of s.structuredContent.results) { const extra = Object.keys(r).filter((k) => !allowed.includes(k)); if (extra.length) throw new Error("extra fields: " + extra); if (!/^\S+( \S\.)?$/u.test(r.name)) throw new Error("surname leak: " + r.name); }
const ir = await call("search_top_candidates", { query: "media buyer", maxResults: 5, includeRate: true }).catch((e) => ({ rejected: e.message }));
if (!ir.rejected) leak("search includeRate", ir);
const f = await call("search_top_candidates", { query: "manager", category: "social-media-managers", maxResults: 3 });
if (f.structuredContent.results.some((r) => r.from !== "social-media-managers")) throw new Error("filter");
const m = await call("match_role", { brief: "Meta and TikTok media buyer for DTC ecommerce brand", maxResults: 5 });
console.log("\n--- match_role ---\n" + m.content[0].text);
if (!m.structuredContent.count) throw new Error("empty match");
leak("match_role", m);
const cats = await call("list_categories", {});
if (cats.structuredContent.categories.length < 20) throw new Error("cats");
const top = m.structuredContent.shortlist[0];
const l = await call("get_candidate_link", { id: top.id, from: top.from });
console.log("\n--- link ---\n" + l.content[0].text);
const p = await call("draft_candidate_pitch", { ...top, category: top.from, roleDescription: "Paid social media buyer scaling a DTC brand", billRate: "$45/hr", includeRate: true });
console.log("\n--- pitch ---\n" + p.content[0].text);
if (/\$|45\/hr|rate|investment/i.test(p.content[0].text + JSON.stringify(p.structuredContent))) throw new Error("pitch leaked price");
for (const t of (await c.listTools()).tools) if (/rate/i.test(JSON.stringify(t.inputSchema))) throw new Error("rate param still in schema: " + t.name);
console.log("\nALL GREEN");
await c.close();
